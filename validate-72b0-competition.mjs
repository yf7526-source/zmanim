import fs from 'node:fs';
import crypto from 'node:crypto';
const read = p => fs.readFileSync(p,'utf8');
const checks = [];
const ok=(name,cond)=>{checks.push([name,!!cond]); if(!cond) console.error('FAIL',name);};
const home=read('src/pages/Home.jsx');
const app=read('src/App.jsx');
const pkg=JSON.parse(read('package.json'));
const cal=read('src/components/JewishCalendarSheet.jsx');
const monthly=read('src/components/MonthlyZmanimSelector.jsx');
const sw=read('public/sw.js');
const sun=fs.readFileSync('src/components/SunCircle.jsx');
const hash=crypto.createHash('sha256').update(sun).digest('hex');
ok('72b0 Home structure preserved', !home.includes('presentationMode') && home.includes('<SunCircle'));
ok('Original SunCircle hash preserved', hash==='4cdf7a39975538030035ce986fbb3a510304ae171da44ba9f7f03f4b6df6bf36');
ok('24-hour preference persists', home.includes('readBoolPref(PREF_KEYS.hour12'));
ok('Location defaults can be disabled', home.includes('followLocationDefaults') && home.includes('if (followLocationDefaults)'));
ok('Shared holiday classifier active', cal.includes('categorizeHebcalEvent'));
ok('Monthly settings synchronization present', monthly.includes('follow') || monthly.includes('Daily Settings'));
ok('PWA service worker present', sw.includes('CACHE_VERSION'));
ok('Compare route present', app.includes('CompareWorkspace'));
ok('Community display route present', app.includes('CommunityDisplay'));
ok('Production package identity', pkg.name==='solarzmanim-72b0-competition' && pkg.version==='1.6.0');
ok('Cloudflare headers present', fs.existsSync('public/_headers'));
ok('Offline fallback present', fs.existsSync('public/offline.html'));
const failed=checks.filter(x=>!x[1]);
console.log(`72B0 competition validation: ${checks.length-failed.length}/${checks.length} passed`);
if(failed.length) process.exit(1);
